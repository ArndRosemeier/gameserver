import { defineConfig } from "vite";
import type { Plugin } from "vite";

// Writes sw.js into the build: a service worker that stores every built file on the first visit,
// so the game also opens with no internet (needed for nearby play, see docs/LOCAL.md).
function offline(): Plugin {
  return {
    name: "arena-offline",
    apply: "build",
    generateBundle(_options, bundle) {
      const files = ["./", ...Object.keys(bundle).map((f) => "./" + f), "./icon.svg", "./manifest.webmanifest"];
      const version = Date.now().toString(36);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: `// generated by vite.config.ts
const CACHE = "arena-${version}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req).catch(() =>
    req.mode === "navigate" ? caches.match("./") : Response.error())));
});
`,
      });
    },
  };
}

// Root is example/; the shared client lives in ../client and is imported directly.
export default defineConfig({
  root: "example",
  // Served from https://apps.futuremagic.de/arena/ - asset URLs must be relative.
  base: "./",
  envDir: ".",
  server: { port: 5174 },
  build: { outDir: "../dist", emptyOutDir: true },
  plugins: [offline()],
});
